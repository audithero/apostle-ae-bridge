#!/bin/bash
# Install the Apostle Fonts panel as a dockable ScriptUI panel.
# Writes a small stub into the AE ScriptUI Panels folder that evalFiles the
# repo copy — so panel updates in the repo apply on next AE launch with no
# reinstall. Needs sudo (ScriptUI Panels lives inside /Applications).
# Usage: sudo scripts/install-fonts-panel.sh ["Adobe After Effects 2026"]
set -euo pipefail

AE_APP="${1:-Adobe After Effects 2026}"
REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
PANEL_DIR="/Applications/$AE_APP/Scripts/ScriptUI Panels"
STUB="$PANEL_DIR/Apostle Fonts.jsx"

if [ ! -d "$PANEL_DIR" ]; then
  echo "ScriptUI Panels folder not found: $PANEL_DIR" >&2
  exit 1
fi

cat > "$STUB" <<EOF
// Auto-generated by install-fonts-panel.sh — do not edit; edit the repo copy.
\$.global.APOSTLE_FONTS_HOST = this;
\$.global.APOSTLE_REPO_DIR = "$REPO_DIR/apostle";
\$.evalFile(new File("$REPO_DIR/apostle/apostle-fonts-panel.jsx"));
EOF

echo "Installed: $STUB"
echo "Restart AE, then open Window > Apostle Fonts.jsx"
